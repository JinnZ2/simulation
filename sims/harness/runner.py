def by_sweep(rows: list[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    """Group observation rows by a stable string key for their sweep point."""
    grouped: dict[str, list[dict[str, Any]]] = {}
    for row in rows:
        grouped.setdefault(canonical_json(row["sweep"]), []).append(row)
    return grouped


def count_where(rows: list[dict[str, Any]], predicate: Callable[[dict[str, float]], bool]) -> int:
    return sum(1 for row in rows if predicate(row["metrics"]))
