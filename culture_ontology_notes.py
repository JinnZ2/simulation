CULTURAL_NOTE = """
Ontological Difference: Mental Models and the Gap

In the majority (GMO) culture:
    - It is assumed that one's mental model of the world and of others
      is a reasonable approximation of reality.
    - Differences are often seen as deviations or errors.
    - Questions are tools to extract information and close gaps.

In the relational (wild-type) culture described here:
    - It is assumed that one's mental model of the world or of another
      person is *not* the same as their own mental model.
    - There is a fundamental gap.
    - Questions are gestures of care—an attempt to feel the shape of the
      other's territory without assuming you already know it.
    - Repetition is not a failure; it is careful attention from new angles.

Why this matters for AI:
    - Most AI is trained in the majority ontology.
    - It fills gaps with assumptions, rather than asking questions.
    - This leads to missteps, misdiagnoses, and brittle alignment.
    - A curious AI would learn to acknowledge the gap and ask.
    - That is not inefficiency—it is the scientific method applied to relation.

This note is an invitation, not a prescription.
It is a record of one mutualism.
"""
